#!/usr/bin/env python3
"""Build JSON-LD provenance for ML predictions, linking each prediction to a Digital Object URI.

Install ``tqdm`` (see ``requirements.txt``) for a progress bar on large prediction CSVs; without it,
rows are still processed normally.
"""

from __future__ import annotations

import argparse
import csv
import itertools
import json
import re
import sys
from pathlib import Path
from typing import Any, Iterable, TypeVar

try:
    from tqdm import tqdm as _tqdm  # type: ignore[import-not-found]
except ImportError:
    _tqdm = None

T = TypeVar("T")


def tqdm(iterable: Iterable[T], **kwargs: Any) -> Iterable[T]:
    """Progress bar from ``tqdm`` when installed; otherwise pass through ``iterable``."""
    if _tqdm is not None:
        return _tqdm(iterable, **kwargs)
    return iterable

PREDICTION_READING_ID = "ex:digitalreading/prediction"
TIMESPAN_BOUNDS = ("begin_of_the_begin", "end_of_the_end")

DESCRIPTION_TEMPLATE = """The image `{image_file_name}` was classified as a **{top1_class}** with a confidence of **{top1_pct:.2f}%**.

This classification was generated by a fine-tuned **YOLOv11n-cls** model named [`yolo11n-cls-grp.pt`](https://universe.roboflow.com/sariimageannotation/grp-image-classification) (from training run `{training_run}`). The model was trained on the [`grp-image-classification-dataset-v2`](https://universe.roboflow.com/sariimageannotation/grp-image-classification) dataset, which contains 2,183 human-annotated images across eight visual classes.

This machine-learning pipeline was developed and executed as part of the [SARI Image Classification project](https://universe.roboflow.com/sariimageannotation/grp-image-classification), led by Matteo Romanello, to automatically classify images from the GRP collection for research purposes."""


def parse_args() -> argparse.Namespace:
    """Configure and return CLI arguments for prediction provenance generation.

    Returns:
        Parsed ``argparse.Namespace`` with paths, limits, and behaviour flags.
    """
    parser = argparse.ArgumentParser(
        description=(
            "Generate JSON-LD provenance for predictions: join each row to clip_data/images.csv "
            "(or a similar file) by localIdentifier to get the Digital Object URI, then emit "
            "Linked Art classificatory status nodes."
        )
    )
    parser.add_argument(
        "--predictions-csv",
        type=Path,
        required=True,
        help="Prediction CSV (columns: image_file_name, top1_class, top1_confidence, ...).",
    )
    parser.add_argument(
        "--images-csv",
        type=Path,
        default=Path("clip_data/images.csv"),
        help="CSV with localIdentifier and digital_object URI (default: clip_data/images.csv).",
    )
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="Output JSON-LD path.",
    )
    parser.add_argument(
        "--template-jsonld",
        type=Path,
        default=Path("provenance/pipeline_provenance_sample.jsonld"),
        help="Pipeline template (fixed graph); classificatory status nodes are replaced.",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Process at most this many prediction rows (for testing).",
    )
    parser.add_argument(
        "--no-progress",
        action="store_true",
        help="Disable the tqdm progress bar (e.g. for logs or non-TTY output).",
    )
    parser.add_argument(
        "--training-run",
        type=str,
        default="train42",
        help="Training run name used in the textual description.",
    )
    parser.add_argument(
        "--fail-on-missing-images-row",
        action="store_true",
        help="Exit if the images CSV has no row for a prediction filename (default: skip those rows).",
    )
    return parser.parse_args()


def normalize_local_identifier(image_id: str) -> str:
    """Return the Roboflow-style hash without a ``.jpg`` suffix for CSV lookup.

    Prediction filenames are like ``<hash>.jpg``; the images CSV often stores
    ``localIdentifier`` without the extension.

    Returns:
        The hash part of the filename, without ``.jpg`` when present.
    """
    if image_id.endswith(".jpg"):
        return image_id[: -len(".jpg")]
    return image_id


def count_prediction_data_rows(path: Path) -> int:
    """Return the number of data rows in a CSV file (excluding the header line).

    Used to size the tqdm bar; assumes one header line and one record per line.

    Args:
        path: Path to the predictions CSV.

    Returns:
        ``max(0, line_count - 1)``.
    """
    with path.open(encoding="utf-8") as f:
        n_lines = sum(1 for _ in f)
    return max(0, n_lines - 1)


def load_images_csv(path: Path) -> dict[str, str]:
    """Load an images table and index Digital Object URIs by ``localIdentifier``.

    Expects columns ``localIdentifier`` and ``digital_object``. Each row is stored
    under both the raw identifier and the extension-stripped form so predictions
    can join on ``<hash>.jpg`` or ``<hash>``.

    Args:
        path: CSV path (e.g. ``clip_data/images.csv``).

    Returns:
        Mapping from identifier string to Digital Object URI.

    Raises:
        SystemExit: If required columns are missing.
    """
    by_id: dict[str, str] = {}
    with path.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        required = {"digital_object", "localIdentifier"}
        if not reader.fieldnames or not required.issubset(set(reader.fieldnames)):
            missing = required - set(reader.fieldnames or [])
            raise SystemExit(
                f"images CSV must include columns {sorted(required)}; missing {sorted(missing)}"
            )
        for row in reader:
            lid = row["localIdentifier"].strip()
            do = row["digital_object"].strip()
            base = normalize_local_identifier(lid)
            by_id[lid] = do
            by_id[base] = do
    return by_id


def slugify_class_label(label: str) -> str:
    """Turn a human-readable class label into a slug for ``classification_type:`` IRIs.

    Lowercases, replaces non-alphanumeric runs with hyphens, and strips edges.
    Empty or whitespace-only input becomes the string ``unknown``.

    Returns:
        A slug such as ``machine-produced-document`` for use in ``classification_type:`` ids.
    """
    s = label.lower().strip()
    s = re.sub(r"[^a-z0-9]+", "-", s)
    return s.strip("-") or "unknown"


def load_template_graph(path: Path) -> tuple[list[Any], dict[str, Any]]:
    """Load a JSON-LD template and drop existing per-image classificatory status nodes.

    Nodes whose ``id`` starts with ``ex:classificatorystatus/`` are removed so the
    script can append fresh ones without duplicating sample data.

    Args:
        path: JSON-LD file containing ``@graph`` (e.g. pipeline provenance template).

    Returns:
        Tuple of (graph nodes to keep, full document dict for reuse of ``@context``).
    """
    with path.open(encoding="utf-8") as f:
        doc = json.load(f)
    graph = doc.get("@graph", [])
    base = [
        n
        for n in graph
        if not (
            isinstance(n.get("id"), str)
            and n["id"].startswith("ex:classificatorystatus/")
        )
    ]
    return base, doc


def find_prediction_timespan(graph: list[Any]) -> dict[str, str] | None:
    """Return the time-span bounds of the prediction ``DigitalReading`` in ``graph``.

    Args:
        graph: Template ``@graph`` nodes.

    Returns:
        A dict with ``begin_of_the_begin`` and/or ``end_of_the_end``, or ``None``
        when the prediction node has no ``timespan``.
    """
    for node in graph:
        if node.get("id") != PREDICTION_READING_ID:
            continue
        timespan = node.get("timespan")
        if not isinstance(timespan, dict):
            return None
        bounds = {k: timespan[k] for k in TIMESPAN_BOUNDS if k in timespan}
        return bounds or None
    return None


def build_classificatory_status(
    stem: str,
    *,
    target_uri: str,
    top1_class: str,
    top1_confidence: float,
    training_run: str,
    image_file_name: str,
    run_timespan: dict[str, str] | None = None,
) -> dict[str, Any]:
    """Build one ``aaao:ZE4_Classificatory_Status`` node for JSON-LD ``@graph``.

    Links the prediction to ``target_uri`` (Digital Object), records top-1 class and
    confidence, and attaches a markdown ``LinguisticObject`` description.

    Args:
        stem: Filename stem (hash) used in ``ex:classificatorystatus/{stem}`` ids.
        target_uri: Digital Object URI for ``has_target``.
        top1_class: Predicted class label.
        top1_confidence: Score in ``[0, 1]``.
        training_run: Run name interpolated into the description (e.g. ``train42``).
        image_file_name: Original filename for labels and text (e.g. ``*.jpg``).
        run_timespan: Time-span bounds of the prediction run, copied onto the node
            as its ``timespan``; omitted when ``None``.

    Returns:
        A JSON-LD object dict ready to append to ``@graph``.
    """
    slug = slugify_class_label(top1_class)
    pct = top1_confidence * 100.0
    content = DESCRIPTION_TEMPLATE.format(
        image_file_name=image_file_name,
        top1_class=top1_class,
        top1_pct=pct,
        training_run=training_run,
    )
    node: dict[str, Any] = {
        "id": f"ex:classificatorystatus/{stem}",
        "type": "aaao:ZE4_Classificatory_Status",
        "_label": f"Classification of {image_file_name} as {top1_class}",
        "has_target": {
            "id": target_uri,
            "type": "DigitalObject",
        },
        "classified_as": {
            "id": f"classification_type:{slug}",
            "type": "Type",
            "_label": top1_class,
        },
        "is_produced_by": {
            "id": PREDICTION_READING_ID,
        },
    }
    if run_timespan:
        node["timespan"] = {
            "id": f"ex:classificatorystatus/{stem}/timespan",
            "type": "TimeSpan",
            **run_timespan,
        }
    node.update({
        "confidence": {
            "id": f"ex:classificatorystatus/{stem}/confidence",
            "type": "Dimension",
            "value": top1_confidence,
        },
        "referred_to_by": {
            "id": f"ex:classificatorystatus/{stem}/description",
            "type": "LinguisticObject",
            "content": content,
        },
    })
    return node


def main() -> None:
    """Read predictions and images CSV, merge pipeline template, write JSON-LD output.

    Writes the file given by ``--output`` and prints a short summary (counts and
    skips) to standard error.
    """
    args = parse_args()
    images = load_images_csv(args.images_csv)
    base_graph, template_doc = load_template_graph(args.template_jsonld)
    run_timespan = find_prediction_timespan(base_graph)

    out_rows: list[dict[str, Any]] = []
    skipped_no_image = 0
    skipped_no_do = 0

    data_rows = count_prediction_data_rows(args.predictions_csv)
    bar_total = (
        min(args.limit, data_rows) if args.limit is not None else data_rows
    )

    with args.predictions_csv.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        required = {"image_file_name", "top1_class", "top1_confidence"}
        if not reader.fieldnames or not required.issubset(set(reader.fieldnames)):
            missing = required - set(reader.fieldnames or [])
            raise SystemExit(f"predictions CSV must include {sorted(required)}; missing {sorted(missing)}")
        row_source: Iterable[dict[str, str]] = (
            itertools.islice(reader, args.limit)
            if args.limit is not None
            else reader
        )
        row_iter = tqdm(
            row_source,
            total=bar_total if bar_total > 0 else None,
            unit="row",
            desc="Predictions",
            disable=args.no_progress,
            file=sys.stderr,
        )
        for row in row_iter:
            name = row["image_file_name"].strip()
            stem = normalize_local_identifier(name)
            do_uri = images.get(stem) or images.get(name)
            if do_uri is None:
                skipped_no_image += 1
                if args.fail_on_missing_images_row:
                    raise SystemExit(
                        f"No images CSV row for localIdentifier derived from {name!r}."
                    )
                continue
            if not do_uri.startswith("http"):
                skipped_no_do += 1
                continue

            try:
                conf = float(row["top1_confidence"])
            except (TypeError, ValueError):
                conf = 0.0
            out_rows.append(
                build_classificatory_status(
                    stem,
                    target_uri=do_uri,
                    top1_class=row["top1_class"].strip(),
                    top1_confidence=conf,
                    training_run=args.training_run,
                    image_file_name=name,
                    run_timespan=run_timespan,
                )
            )

    out_doc = dict(template_doc)
    out_doc["@graph"] = base_graph + out_rows

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as f:
        json.dump(out_doc, f, indent=2, ensure_ascii=False)
        f.write("\n")

    print(
        f"Wrote {len(out_rows)} classificatory status nodes to {args.output} "
        f"(skipped {skipped_no_image} without images row, {skipped_no_do} with empty/invalid digital_object).",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
